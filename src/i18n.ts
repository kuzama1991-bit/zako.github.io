export type Lang = keyof typeof UI;
export type TKey = keyof typeof UI.en;

export function t(lang: Lang, key: TKey): string {
  return (UI[lang] as any)[key] ?? UI.en[key];
}

export function langLabel(code: LangCode, currentLang: Lang): string {
  const lang = LANGUAGES.find(l => l.code === code);
  if (!lang) return code;
  return (lang.label as any)[currentLang] ?? lang.label.en;
}

export function langFlag(code: LangCode): string {
  const lang = LANGUAGES.find(l => l.code === code);
  return lang?.flag ?? '';
}
